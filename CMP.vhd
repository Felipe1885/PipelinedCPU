LIBRARY ieee;
USE ieee.std_logic_1164.all;

ENTITY CMP  IS
PORT ( X: IN STD_LOGIC_VECTOR (15 DOWNTO 0);
		 Y: IN STD_LOGIC_VECTOR (15 DOWNTO 0); 
		 EQ: OUT STD_LOGIC;
		 G: OUT STD_LOGIC;
		 L: OUT STD_LOGIC);
END CMP;

ARCHITECTURE Structure OF CMP  IS
	SIGNAL P: STD_LOGIC_VECTOR(15 DOWNTO 0);
	SIGNAL T1, T2 :STD_LOGIC;
BEGIN

	P(0)  <= X(0)  XNOR Y(0);
	P(1)  <= X(1)  XNOR Y(1);
	P(2)  <= X(2)  XNOR Y(2);
	P(3)  <= X(3)  XNOR Y(3);
	P(4)  <= X(4)  XNOR Y(4);
	P(5)  <= X(5)  XNOR Y(5);
	P(6)  <= X(6)  XNOR Y(6);
	P(7)  <= X(7)  XNOR Y(7);
	P(8)  <= X(8)  XNOR Y(8);
	P(9)  <= X(9)  XNOR Y(9);
	P(10) <= X(10) XNOR Y(10);
	P(11) <= X(11) XNOR Y(11);
	P(12) <= X(12) XNOR Y(12);
	P(13) <= X(13) XNOR Y(13);
	P(14) <= X(14) XNOR Y(14);
	P(15) <= X(15) XNOR Y(15);
 
T1 <= P(0) AND P(1) AND P(2) AND P(3) AND 
          P(4) AND P(5) AND P(6) AND P(7) AND 
          P(8) AND P(9) AND P(10) AND P(11) AND 
          P(12) AND P(13) AND P(14) AND P(15);

T2 <= (X(15) AND (NOT Y(15))) OR
		(P(15) AND X(14) AND (NOT Y(14))) OR
		(P(15) AND P(14) AND X(13) AND (NOT Y(13))) OR
		(P(15) AND P(14) AND P(13) AND X(12) AND (NOT Y(12))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND X(11) AND (NOT Y(11))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND X(10) AND (NOT Y(10))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND X(9) AND (NOT Y(9))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND X(8) AND (NOT Y(8))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND X(7) AND (NOT Y(7))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND X(6) AND (NOT Y(6))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND P(6) AND X(5) AND (NOT Y(5))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND P(6) AND P(5) AND X(4) AND (NOT Y(4))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND P(6) AND P(5) AND P(4) AND X(3) AND (NOT Y(3))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND P(6) AND P(5) AND P(4) AND P(3) AND X(2) AND (NOT Y(2))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND P(6) AND P(5) AND P(4) AND P(3) AND P(2) AND X(1) AND (NOT Y(1))) OR
		(P(15) AND P(14) AND P(13) AND P(12) AND P(11) AND P(10) AND P(9) AND P(8) AND P(7) AND P(6) AND P(5) AND P(4) AND P(3) AND P(2) AND P(1) AND X(0) AND (NOT Y(0)));

	EQ <= T1;
	G <= T2;

	L <= (T1 NOR T2);
	
END Structure;